"""Smoke Playwright contra browser_mexc_readonly_server (bóveda temporal)."""

from playwright.sync_api import expect, sync_playwright


with sync_playwright() as playwright:
    browser = playwright.chromium.launch(headless=True)
    page = browser.new_page()
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.goto("http://127.0.0.1:8799/ui/#/real")
    page.wait_for_load_state("networkidle")
    page.locator("#real-passphrase").fill("browser smoke secret 123")
    page.locator("#real-passphrase-confirm").fill("browser smoke secret 123")
    page.get_by_role("button", name="Crear bóveda").click()
    page.locator("#real-new-account").wait_for()
    page.locator('#real-new-account [name="name"]').fill("Principal")
    page.get_by_role("button", name="Crear cuenta").click()
    page.locator("#real-mexc-connect").wait_for()
    page.get_by_text("Sin conexión. Introduce una clave nueva, solo lectura.").wait_for()
    page.locator("#real-mexc-connect summary").click()
    page.locator('#real-mexc-form [name="api_key"]').fill("browser-test-key")
    page.locator('#real-mexc-form [name="secret_key"]').fill("browser-test-secret")
    with page.expect_response("**/real/exchanges/mexc/connect") as connection:
        page.get_by_role("button", name="Consultar MEXC").click()
    assert connection.value.status == 200, connection.value.text()
    page.get_by_text("0.26", exact=True).wait_for()
    assert page.locator('#real-mexc-form [name="api_key"]').input_value() == ""
    assert page.locator('#real-mexc-form [name="secret_key"]').input_value() == ""
    page.locator("#real-mexc-identity summary").click()
    page.get_by_role("button", name="Comprobar cuenta").click()
    expect(page.locator("#real-mexc-identity-result")).to_contain_text("Sin huella local previa")
    assert "209302839" not in page.locator("#real-mexc-identity-result").inner_text()
    page.get_by_role("button", name="Comparar inventario").click()
    expect(page.locator("#real-mexc-comparison")).to_contain_text("vínculo de cuenta no verificado")
    expect(page.locator("#real-mexc-comparison")).to_contain_text("0.26")
    assert "Sin asientos ni órdenes" in page.locator("#real-mexc-comparison").inner_text()
    first_account = page.locator("#real-account").input_value()
    page.locator("#real-add-account summary").click()
    page.locator('#real-add-account-form [name="name"]').fill("Otra cuenta")
    page.locator("#real-add-account-form").get_by_role("button", name="Crear cuenta").click()
    expect(page.locator("#real-account")).not_to_have_value(first_account)
    page.get_by_role("button", name="Comparar inventario").click()
    expect(page.locator("#real-mexc-comparison")).to_contain_text("vínculo de cuenta no verificado")
    page.locator("#real-account").select_option(first_account)
    assert page.locator("#real-mexc-comparison").is_hidden()
    page.get_by_role("button", name="Valorar").click()
    expect(page.locator("#real-mexc-value-state")).to_contain_text("26100.00")
    headers = page.locator("#real-mexc-state th").all_inner_texts()
    assert "VALOR USDT" in headers, headers
    page.get_by_role("button", name="Actualizar saldos").click()
    expect(page.locator("#real-mexc-value-state")).to_contain_text("Elige divisa y pulsa Valorar")
    assert "VALOR USDT" not in page.locator("#real-mexc-state").inner_text()
    page.locator("#real-mexc-value-quote").select_option("EUR")
    page.get_by_role("button", name="Valorar").click()
    expect(page.locator("#real-mexc-value-state")).to_contain_text("Total no disponible")
    assert "BTC" in page.locator("#real-mexc-value-state").inner_text()
    page.locator("#real-mexc-value-quote").select_option("USDT")
    page.get_by_role("button", name="Valorar").click()
    expect(page.locator("#real-mexc-value-state")).to_contain_text("26100.00")
    page.get_by_text("Todavía no hay posiciones.").wait_for()
    page.get_by_text("Todavía no hay movimientos.").wait_for()
    page.get_by_role("button", name="Última página").click()
    page.get_by_text("browser-fill-1", exact=True).wait_for()
    assert "historial parcial · no importado" in page.locator("#real-mexc-trades").inner_text()
    assert "1 nuevos guardados" in page.locator("#real-mexc-trades").inner_text()
    page.get_by_role("button", name="Archivar rango").click()
    expect(page.locator("#real-mexc-trades")).to_contain_text("1 fills observados")
    assert page.get_by_text("Todavía no hay movimientos.").count() == 1
    page.get_by_role("button", name="Consultar y guardar").click()
    expect(page.locator("#real-mexc-transfer-result")).to_contain_text("0.125", timeout=10000)
    assert "instantánea cifrada, no contabilizada" in page.locator("#real-mexc-transfer-result").inner_text()
    page.locator("#real-mexc-transfers-archive summary").click()
    page.locator("#real-mexc-transfers-list button").first.wait_for()
    page.locator("#real-mexc-transfers-list button").first.click()
    page.locator("#real-mexc-transfers-detail").get_by_text("0.125", exact=True).wait_for()
    page.locator("#real-mexc-transfer-days").select_option("30")
    page.get_by_role("button", name="Consultar y guardar").click()
    expect(page.locator("#real-mexc-transfer-result")).to_contain_text("10 consultas")
    page.locator("#real-mexc-transfer-days").select_option("90")
    page.get_by_role("button", name="Consultar y guardar").click()
    expect(page.locator("#real-mexc-transfer-result")).to_contain_text("26 consultas")
    page.get_by_role("button", name="Ocultar importes").click()
    page.locator("#real-mexc-state").get_by_text("••••").first.wait_for()
    page.get_by_role("button", name="Comparar inventario").click()
    expect(page.locator("#real-mexc-comparison")).to_contain_text("••••")
    assert "0.26" not in page.locator("#real-mexc-comparison").inner_text()
    page.get_by_role("button", name="Valorar").click()
    expect(page.locator("#real-mexc-value-state")).to_contain_text("••••")
    assert "26100.00" not in page.locator("#real-mexc-value-state").inner_text()
    assert page.locator("#real-mexc-state").get_by_text("0.26", exact=True).count() == 0
    page.get_by_role("button", name="Última página").click()
    page.locator("#real-mexc-trades").get_by_text("••••").first.wait_for()
    assert "25.125" not in page.locator("#real-mexc-trades").inner_text()
    assert "0 nuevos guardados" in page.locator("#real-mexc-trades").inner_text()
    page.get_by_role("button", name="Consultar y guardar").click()
    page.locator("#real-mexc-transfer-result").get_by_text("••••").first.wait_for()
    assert "0.125" not in page.locator("#real-mexc-transfer-result").inner_text()
    page.locator("#real-mexc-archive summary").click()
    page.locator("#real-mexc-archive-list button").first.wait_for()
    page.locator("#real-mexc-archive-list button").first.click()
    page.locator("#real-mexc-archive-detail").get_by_text("browser-fill-1", exact=True).wait_for()
    expect(page.locator("#real-mexc-archive-detail [data-coverage]")).to_contain_text(
        "sin huecos entre")
    expect(page.locator("#real-mexc-archive-detail [data-coverage]")).to_contain_text(
        "No acredita historial anterior ni conciliación")
    page.locator("#real-mexc-transfers-archive summary").click()
    page.locator("#real-mexc-transfers-list button").first.wait_for()
    page.locator("#real-mexc-transfers-list button").first.click()
    page.locator("#real-mexc-transfers-detail").get_by_text("••••").first.wait_for()
    assert "25.125" not in page.locator("#real-mexc-archive-detail").inner_text()
    page.get_by_role("button", name="Desconectar").click()
    page.get_by_text("Desconectado. Clave retirada de la sesión.").wait_for()
    assert page.locator("#real-mexc-value").is_hidden()
    assert page.locator("#real-mexc-value-state").inner_text() == ""
    assert page.locator("#real-mexc-trades").is_hidden()
    assert page.locator("#real-mexc-transfer-result").is_hidden()
    assert page.locator("#real-mexc-comparison").is_hidden()
    assert page.locator("#real-mexc-identity").is_hidden()
    page.get_by_role("button", name="Bloquear").click()
    page.locator("#real-passphrase").wait_for()
    page.locator("#real-passphrase").fill("browser smoke secret 123")
    page.get_by_role("button", name="Desbloquear").click()
    page.locator("#real-mexc-archive summary").wait_for()
    page.get_by_text("Sin conexión. Introduce una clave nueva, solo lectura.").wait_for()
    page.locator("#real-mexc-archive summary").click()
    page.locator("#real-mexc-archive-list button").first.wait_for()
    page.locator("#real-mexc-archive-list button").first.click()
    page.locator("#real-mexc-archive-detail").get_by_text("browser-fill-1", exact=True).wait_for()
    expect(page.locator("#real-mexc-archive-detail [data-coverage]")).to_contain_text(
        "sin huecos entre")
    page.locator("#real-mexc-transfers-archive summary").click()
    page.locator("#real-mexc-transfers-list button").first.wait_for()
    page.locator("#real-mexc-transfers-list button").first.click()
    page.locator("#real-mexc-transfers-detail").get_by_text("••••").first.wait_for()
    assert not errors, errors
    print("Browser MEXC read-only flow passed: valuation, balances, fills, transfers, hide, disconnect, lock")
    browser.close()
